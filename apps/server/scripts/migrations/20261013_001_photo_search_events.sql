CREATE TABLE IF NOT EXISTS photo_search_events (
  event_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  organization_id INT UNSIGNED NOT NULL,
  unit_id INT UNSIGNED NULL,
  project_id INT UNSIGNED NULL,
  query_text VARCHAR(160) NOT NULL,
  requested_ai TINYINT(1) NOT NULL DEFAULT 0,
  search_mode VARCHAR(16) NULL,
  ai_used TINYINT(1) NOT NULL DEFAULT 0,
  cache_hit TINYINT(1) NOT NULL DEFAULT 0,
  degraded TINYINT(1) NOT NULL DEFAULT 0,
  relaxed TINYINT(1) NOT NULL DEFAULT 0,
  result_count INT UNSIGNED NULL,
  duration_ms INT UNSIGNED NOT NULL,
  query_plan JSON NULL,
  original_plan JSON NULL,
  error_code VARCHAR(32) NULL,
  created_at DATETIME(3) NOT NULL,
  expires_at DATETIME(3) NOT NULL,
  PRIMARY KEY (event_id),
  KEY idx_photo_search_events_org_time (organization_id, created_at),
  KEY idx_photo_search_events_unit_time (organization_id, unit_id, created_at),
  KEY idx_photo_search_events_expiry (expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
