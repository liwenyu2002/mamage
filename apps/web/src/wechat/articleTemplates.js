// 从任意文本里提取 {{占位符}} 键列表（去重、保序）
export function extractPlaceholders(text) {
  const out = [];
  const seen = new Set();
  const re = /\{\{([^{}]{2,40})\}\}/g;
  let m;
  while ((m = re.exec(String(text || '')))) {
    const key = m[1].trim();
    if (key && !seen.has(key)) {
      seen.add(key);
      out.push(key);
    }
  }
  return out;
}
